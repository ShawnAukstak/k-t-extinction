#!/usr/bin/env python3
"""Rotate the curated points of interest to their 65 Ma positions with the PALEOMAP plate model.

    .venv/bin/python scripts/reconstruct_pois.py

Uses scripts/kt/plates.py (an offline implementation that reproduces the GPlates Web Service's
PALEOMAP reconstructions exactly; see test_plates in scripts/tests). Reads
data/curated/points-of-interest.yaml and writes data/curated/points-of-interest.reconstructed.yaml
(committed: small, records model/time/date).
"""
from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kt.paths import CURATED  # noqa: E402
from kt.plates import PlateModel  # noqa: E402


def main() -> None:
    src = yaml.safe_load((CURATED / "points-of-interest.yaml").read_text())
    rec = src["reconstruction"]
    if rec["model"] != "PALEOMAP":
        raise SystemExit("only the PALEOMAP model is implemented offline")
    model = PlateModel()
    out_pts = {}
    for p in src["points"]:
        la, lo, plate = model.reconstruct(p["modern"]["lat"], p["modern"]["lon"], rec["time_ma"])
        if plate is None:
            raise SystemExit(f"{p['id']}: not on any plate polygon")
        out_pts[p["id"]] = {"lat": round(la, 4), "lon": round(lo, 4), "plate": plate}
        print(f"{p['id']:16s} plate {plate:4d}  {p['modern']['lat']:8.3f},{p['modern']['lon']:9.3f} → {la:8.3f},{lo:9.3f}")
    out = {"model": rec["model"], "time_ma": rec["time_ma"], "computed": dt.date.today().isoformat(),
           "method": "scripts/kt/plates.py (offline; matches GPlates Web Service)", "points": out_pts}
    dest = CURATED / "points-of-interest.reconstructed.yaml"
    dest.write_text("# Generated by scripts/reconstruct_pois.py — do not edit by hand.\n" + yaml.safe_dump(out, sort_keys=False))
    print("wrote", dest)


if __name__ == "__main__":
    main()
